def get_yao_ci(hexagram_name: str, line_position: str) -> tuple[str, str]:
    """
    获取特定爻位的爻辞。

    Args:
        hexagram_name: 卦名（支持全称或简称）
        line_position: 爻位（如 "初九", "六二", "九三", "六四", "九五", "上九"）

    Returns:
        (yao_ci_text, source)
    """
    resolved = _resolve_hexagram(hexagram_name)
    yao_list = YAO_CI.get(resolved)
    if not yao_list:
        return ("", "")

    # 标准化爻位名称
    idx = _LINE_NAME_TO_INDEX.get(line_position)
    if idx is None or idx >= len(yao_list):
        return ("", "")

    _, position_name, text, source = yao_list[idx]
    return (text, source)


def _resolve_hexagram(name: str) -> str:
    """Resolve hexagram name variant to canonical form."""
    if name in YAO_CI:
        return name
    canonical = _HEXAGRAM_VARIANTS.get(name)
    if canonical and canonical in YAO_CI:
        return canonical
    return name


def get_all_yao_ci(hexagram_name: str) -> list[dict]:
    """Get all 6 yao ci for a hexagram."""
    resolved = _resolve_hexagram(hexagram_name)
    yao_list = YAO_CI.get(resolved, [])
    return [{"position": p, "text": t, "source": s} for _, p, t, s in yao_list]
