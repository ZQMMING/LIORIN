# 四、岁运恶力 (L4276 恶运分数档) + 吉力
# ============================================================================
def year_power(verdicts) -> dict:
    """流年凶力/吉力: Σ强度分 → (恶力, 恶力档, 吉力).

    恶力档 (对应 L4276): 轻 Y<=3 / 中 4<=Y<=6 / 重 Y>=7.
    """
    xiong = 0.0
    ji = 0.0
    zhi = 0.0
    for v in verdicts:
        rid = v.get("rule_id", "")
        tone = v.get("tone", "平")
        if tone == "凶":
            xiong += YEAR_XIONG.get(rid, 2)
        elif tone == "吉":
            ji += YEAR_XI.get(rid, 2)
        elif tone == "滞":
            zhi += 0.5
    if xiong <= 3:
        yl = "轻"
    elif xiong <= 6:
        yl = "中"
    else:
        yl = "重"
    return {"xiong": round(xiong, 2), "ji": round(ji, 2), "zhi": zhi,
            "level": yl}


