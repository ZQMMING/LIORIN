def aggregate(base: dict, power: dict, dim_hits: dict | None = None,
              luck_level: str = "平") -> dict:
    """L4276 查表 + 吉力微调 + L4273 运主年辅 + 重维度修正.

    - L4273 运主年辅: 大运为十年基调 — 吉运中遇太岁刑害 = 细累浮灾(恶力降级);
      凶运中遇太岁刑冲 = 方可发祸(恶力升级); 平运不变.
    - 吉力微调: 流年吉力≥4 且 恶力为轻 → 升一档 (吉力盖轻恶, 厚福/中福皆然);
    - 重维度修正: 自身婚姻/情性健康 维度凶信号在场且恶力为轻 → 不因厚福掩盖,
      判"吉凶相杂" (L4273 吉运中遇刑害仍细累浮灾 — 细累即相杂, 不上报重灾).
    """
    eff = power["level"]
    if luck_level == "吉":       # L4273: 吉运中刑害 → 细累浮灾 (降级)
        # 仅限 轻/中 恶力降级; 重恶 (七分恶运=重灾级: 死绝会集/元辰/天罗/冲运/晦气)
        # 不因运吉而降 — L4273"细累浮灾"针对刑害级小扰, 重灾级仍报重灾
        # (毛1976 辰年: 冲年+压运+空亡+克命 重恶9 在吉运中仍判凶, 不被运吉拉平)
        eff = {"轻": "轻", "中": "轻", "重": "重"}.get(eff, eff)
    elif luck_level == "凶":     # L4273: 凶运中刑冲 → 发祸 (升级)
        eff = {"轻": "中", "中": "重", "重": "重"}.get(eff, eff)
    v = L4276_TABLE.get((base["level"], eff), "凶")
    if power["ji"] >= 4 and eff == "轻":
        if v == "吉凶相杂":
            v = "吉"
        elif v == "凶" and base["level"] != "薄":
            v = "吉凶相杂"
    if dim_hits:
        heavy = any(dim_hits.get(d) for d in ("自身婚姻", "情性健康"))
        if heavy and eff == "轻" and v == "吉":
            v = "吉凶相杂"  # L4273 吉运中遇刑害 → 细累浮灾 (不上报重灾, 也不全吉)
    return {"verdict": v,
            "base_level": base["level"], "base_score": base["score"],
            "year_level": power["level"], "year_xiong": power["xiong"],
            "year_ji": power["ji"], "eff_level": eff}


def dim_hits_of(verdicts) -> dict:
    """流年断语维度命中表 (V51 按 target 中的柱位动态归属)."""
    hits = {}
    for v in verdicts:
        rid = v.get("rule_id", "")
        dim = DIMENSION.get(rid)
        if dim is None and rid == "LM-V51":
            tgt = v.get("target", "")
            for cn, py in (("年", "父母祖业"), ("月", "兄弟事业"),
                           ("日", "自身婚姻"), ("时", "子女晚年")):
                if cn in tgt:
                    dim = py
                    break
        if dim and dim != "综合贵贱":
            hits.setdefault(dim, []).append(rid)
    return hits
