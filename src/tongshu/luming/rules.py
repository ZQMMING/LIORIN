# ---------------------------------------------------------------- 谓词求值 --
# 求值对象 obj: scalar→ctx / per_pillar→pv / per_list→{**ctx, **item}


def eval_cond(cond, obj):
    op = cond["op"]
    if op == "eq":
        return obj.get(cond["k"]) == cond["v"]
    if op == "in":
        return obj.get(cond["k"]) in cond["v"]
    if op == "gte":
        return (obj.get(cond["k"]) or 0) >= cond["v"]
    if op == "contains_any":
        return bool(set(obj.get(cond["k"]) or []) & set(cond["v"]))
    if op == "and":
        return all(eval_cond(c, obj) for c in cond["conds"])
    if op == "or":
        return any(eval_cond(c, obj) for c in cond["conds"])
    if op == "not":
        return not eval_cond(cond["cond"], obj)
    if op == "not_empty":
        return bool(obj.get(cond["k"]))
    raise ValueError(f"unknown cond op: {op}")


