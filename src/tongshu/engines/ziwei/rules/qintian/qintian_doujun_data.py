def get_doujun_jieyi(palace_name: str):
    """取生年斗君在某宫的解义原文"""
    return DOUJUN_JIEYI.get(palace_name)


def get_doujun_weight(palace_name: str):
    """取某宫为 100% 时的对待宫（70%）"""
    for a, b, wa, wb in DOUJUN_WEIGHT_PAIRS:
        if a == palace_name:
            return {"palace": b, "weight": wb}
