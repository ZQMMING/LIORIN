def get_hou(index: int) -> HouEntry:
    """按全年序号取候（0-71）。"""
    if not 0 <= index < 72:
        raise ValueError(f"index must be 0..71, got {index}")
    return HOU_72_TABLE[index]


def get_hou_by_wuhou(wuhou: str) -> HouEntry:
    """按物候名取候，如 ``get_hou_by_wuhou("蚯蚓结")``。"""
    for h in HOU_72_TABLE:
        if h.wuhou == wuhou:
            return h
    raise ValueError(f"未知物候：{wuhou}")


def get_hou_by_jq(jq_name: str) -> tuple[HouEntry, ...]:
    """取某节气下的三候。"""
    return tuple(h for h in HOU_72_TABLE if h.jq_name == jq_name)


