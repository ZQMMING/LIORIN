"""
L4 调候层(穷通宝鉴查表法)
最小实现: 日主×月令→调候干集合→判定有无
"""

# 调候用神表(穷通宝鉴, 逐干逐月)
# 格式: {日主: {月令: [调候干列表]}}
TIAOHOU_TABLE = {
    '甲': {
        '寅': ['丙', '癸'],
        '卯': ['丙', '癸'],
        '辰': ['庚', '壬', '癸'],
        '巳': ['癸', '丁', '庚'],
        '午': ['癸', '丁'],
        '未': ['癸', '丁'],
        '申': ['丁', '庚'],
        '酉': ['丁', '庚'],
        '戌': ['癸', '丁'],
        '亥': ['庚', '丁'],
        '子': ['丁', '庚'],
        '丑': ['丁', '庚'],
    },
    '乙': {
        '寅': ['丙', '癸'],
        '卯': ['丙', '癸'],
        '辰': ['丙', '癸'],
        '巳': ['癸', '丙'],
        '午': ['癸', '丙'],
        '未': ['癸', '丙'],
        '申': ['丙', '癸'],
        '酉': ['丙', '癸'],
        '戌': ['癸', '丙'],
        '亥': ['丙', '戊'],
        '子': ['丙', '戊'],
        '丑': ['丙', '戊'],
    },
    '丙': {
        '寅': ['壬', '庚'],
        '卯': ['壬', '庚'],
        '辰': ['壬', '甲'],
        '巳': ['壬', '庚'],
        '午': ['壬', '庚'],
        '未': ['壬', '庚'],
        '申': ['壬', '甲'],
        '酉': ['壬', '甲'],
        '戌': ['壬', '甲'],
        '亥': ['壬', '甲'],
        '子': ['壬', '甲'],
        '丑': ['壬', '甲'],
    },
}


def check_tiaohou(day_master, month_branch, four_stems):
    """
    调候检查
    返回: (调候干有无, 调候干列表)
    """
    dm_table = TIAOHOU_TABLE.get(day_master, {})
    tiao_gan_list = dm_table.get(month_branch, [])

    if not tiao_gan_list:
        return '无', []

    has_tiao = [g for g in tiao_gan_list if g in four_stems]
    return '有' if has_tiao else '无', tiao_gan_list


